create table if not exists public.tradingview_signal_events (
  id bigint generated by default as identity primary key,
  secret_hash text not null,
  strategy_id text not null,
  signal_id text not null,
  source text not null default 'TRADINGVIEW',
  symbol text not null,
  action text not null,
  received_at timestamptz not null,
  signal_timestamp timestamptz,
  price numeric,
  status text not null,
  accepted boolean not null default false,
  execution_mode text not null,
  stage text not null,
  reason text,
  signal jsonb not null default '{}'::jsonb,
  decision jsonb not null default '{}'::jsonb,
  raw_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (secret_hash, strategy_id, signal_id)
);

alter table public.tradingview_signal_events enable row level security;

-- Webhook events are written and read by server API routes using the service role key.
-- No anon/authenticated client policies are created here, so browser clients cannot
-- read another user's signal history directly from Supabase.

create index if not exists tradingview_signal_events_secret_received_idx
on public.tradingview_signal_events (secret_hash, received_at desc);

create index if not exists tradingview_signal_events_strategy_signal_idx
on public.tradingview_signal_events (strategy_id, signal_id);
